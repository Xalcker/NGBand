/* Tipos básicos sin dependencia de hardware (compilan en 68000 y en el host). */
#ifndef NGBAND_TYPES_H
#define NGBAND_TYPES_H

#include <stdint.h>
#include <stdbool.h>

typedef uint8_t  u8;
typedef uint16_t u16;
typedef uint32_t u32;
typedef int8_t   s8;
typedef int16_t  s16;
typedef int32_t  s32;

#endif /* NGBAND_TYPES_H */
